"""
Security Middleware

Three concerns, each as its own middleware so they can be reasoned about
and tested independently:

* SecurityHeadersMiddleware — CSP and the other response headers that make
  the browser an ally rather than a liability.
* BodyLimitMiddleware — rejects oversized requests before the body is read
  into memory.
* RequestContextMiddleware — assigns a request ID and emits one structured
  log line per request, carrying no user content.
"""

from __future__ import annotations

import logging
import secrets
import time

from starlette.middleware.base import BaseHTTPMiddleware
from starlette.requests import Request
from starlette.responses import JSONResponse, Response
from starlette.types import ASGIApp

from app.config import settings

logger = logging.getLogger("app.request")


# ── Content Security Policy ──────────────────────────────────────

def _build_csp() -> str:
    """
    Assemble the CSP.

    Notable choices:

    * `script-src 'self'` with no 'unsafe-inline' and no 'unsafe-eval'. The
      templates carry zero inline script, which is what makes this possible.
    * `style-src` needs 'unsafe-inline' because the UI animates a handful of
      element styles from JavaScript (transforms, custom properties for
      parallax). Inline *styles* cannot execute script, so this is a far
      weaker concession than an inline script allowance would be. All
      stylesheets themselves come from 'self' and the Google Fonts CSS host.
    * `connect-src 'self'` — the page only ever talks to its own API.
    * `object-src 'none'` and `base-uri 'none'` close off plugin and
      base-tag injection.
    * `frame-ancestors 'none'` is the modern replacement for
      X-Frame-Options and prevents clickjacking.
    """
    directives = [
        "default-src 'self'",
        "script-src 'self'",
        "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
        "font-src 'self' https://fonts.gstatic.com data:",
        # Thumbnails come from YouTube's image CDN; data: covers inline SVG
        # textures generated by the stylesheet.
        "img-src 'self' data: https://i.ytimg.com https://img.youtube.com",
        "connect-src 'self'",
        "media-src 'none'",
        "object-src 'none'",
        "base-uri 'none'",
        "form-action 'self'",
        "frame-ancestors 'none'",
        "frame-src 'none'",
        "worker-src 'self'",
        "manifest-src 'self'",
    ]

    if settings.force_https:
        directives.append("upgrade-insecure-requests")

    return "; ".join(directives)


_CSP_VALUE = _build_csp()

_PERMISSIONS_POLICY = ", ".join([
    "accelerometer=()",
    "ambient-light-sensor=()",
    "autoplay=()",
    "camera=()",
    "display-capture=()",
    "encrypted-media=()",
    "geolocation=()",
    "gyroscope=()",
    "magnetometer=()",
    "microphone=()",
    "midi=()",
    "payment=()",
    "usb=()",
    "xr-spatial-tracking=()",
])


class SecurityHeadersMiddleware(BaseHTTPMiddleware):
    """Attach security headers to every response, including error responses."""

    async def dispatch(self, request: Request, call_next):
        response: Response = await call_next(request)

        response.headers["Content-Security-Policy"] = _CSP_VALUE
        response.headers["X-Content-Type-Options"] = "nosniff"
        response.headers["Referrer-Policy"] = "strict-origin-when-cross-origin"
        response.headers["Permissions-Policy"] = _PERMISSIONS_POLICY
        # Redundant with CSP frame-ancestors, but still honoured by older browsers.
        response.headers["X-Frame-Options"] = "DENY"
        response.headers["Cross-Origin-Opener-Policy"] = "same-origin"
        response.headers["Cross-Origin-Resource-Policy"] = "same-origin"
        response.headers["X-Permitted-Cross-Domain-Policies"] = "none"

        if settings.force_https:
            response.headers["Strict-Transport-Security"] = (
                f"max-age={settings.hsts_max_age}; includeSubDomains"
            )

        # API responses are per-request and may reflect user content; keep
        # them out of shared and browser caches.
        if request.url.path.startswith("/api/"):
            response.headers["Cache-Control"] = "no-store, no-cache, must-revalidate, private"
            response.headers["Pragma"] = "no-cache"

        # Don't advertise the server implementation.
        if "server" in response.headers:
            del response.headers["server"]

        return response


class BodyLimitMiddleware(BaseHTTPMiddleware):
    """
    Reject oversized request bodies.

    Content-Length is checked first so an obviously-too-large request is
    refused without reading anything. A chunked request without the header
    still gets caught downstream by the body read in the route, which is why
    the limit is also enforced there.
    """

    def __init__(self, app: ASGIApp, max_bytes: int | None = None) -> None:
        super().__init__(app)
        self.max_bytes = max_bytes or settings.max_request_bytes

    async def dispatch(self, request: Request, call_next):
        if request.method in {"POST", "PUT", "PATCH"}:
            content_length = request.headers.get("content-length")
            if content_length:
                try:
                    declared = int(content_length)
                except ValueError:
                    return JSONResponse(
                        status_code=400,
                        content={"error": "Malformed request."},
                    )
                if declared > self.max_bytes:
                    return JSONResponse(
                        status_code=413,
                        content={"error": "Request body is too large."},
                    )

            # Only JSON is accepted on the API surface.
            if request.url.path.startswith("/api/"):
                content_type = (request.headers.get("content-type") or "").split(";")[0].strip().lower()
                if content_type and content_type != "application/json":
                    return JSONResponse(
                        status_code=415,
                        content={"error": "Unsupported content type. Send application/json."},
                    )

        return await call_next(request)


class RequestContextMiddleware(BaseHTTPMiddleware):
    """
    Assign a request ID and log one structured line per request.

    The log line carries only non-sensitive metadata: no bodies, no URLs
    beyond the route path, no transcript text, no headers. The request ID is
    echoed to the client so a user can quote it in a support request without
    us having to expose any internal detail in the error message itself.
    """

    async def dispatch(self, request: Request, call_next):
        request_id = secrets.token_hex(8)
        request.state.request_id = request_id
        started = time.perf_counter()

        try:
            response: Response = await call_next(request)
        except Exception:
            duration_ms = (time.perf_counter() - started) * 1000
            logger.exception(
                "request failed",
                extra={
                    "request_id": request_id,
                    "endpoint": request.url.path,
                    "method": request.method,
                    "status_code": 500,
                    "duration_ms": round(duration_ms, 2),
                },
            )
            raise

        duration_ms = (time.perf_counter() - started) * 1000
        response.headers["X-Request-ID"] = request_id

        logger.info(
            "request",
            extra={
                "request_id": request_id,
                "endpoint": request.url.path,
                "method": request.method,
                "status_code": response.status_code,
                "duration_ms": round(duration_ms, 2),
            },
        )
        return response
